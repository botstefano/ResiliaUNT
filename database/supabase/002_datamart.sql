/*
  RESILIAUNT — DataMart dimensional.
  Mantiene las 8 dimensiones del diseño y separa las medidas que tienen granos distintos.
*/

create table if not exists datamart_resiliencia.dim_tiempo (
  tiempo_key integer primary key,
  fecha date not null unique,
  dia smallint not null,
  mes smallint not null,
  nombre_mes varchar(12) not null,
  trimestre smallint not null,
  anio smallint not null
);

create table if not exists datamart_resiliencia.dim_estudiante (
  estudiante_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  id_estudiante_oltp bigint unique,
  codigo_universitario varchar(20) unique not null,
  carrera varchar(100),
  ciclo_academico smallint,
  turno varchar(20)
);

create table if not exists datamart_resiliencia.dim_terapeuta (
  terapeuta_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  codigo_terapeuta varchar(30) unique not null,
  nombre varchar(150),
  especialidad varchar(100)
);

create table if not exists datamart_resiliencia.dim_sala_terapia (
  sala_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  codigo_sala varchar(30) unique not null,
  nombre_sala varchar(100),
  pabellon varchar(100),
  modalidad varchar(30)
);

create table if not exists datamart_resiliencia.dim_habito (
  habito_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  codigo_habito varchar(30) unique not null,
  nombre varchar(100),
  categoria varchar(50)
);

create table if not exists datamart_resiliencia.dim_intensidad (
  intensidad_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  nivel varchar(20) unique not null
);

create table if not exists datamart_resiliencia.dim_meta_categoria (
  meta_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  categoria varchar(50) unique not null
);

create table if not exists datamart_resiliencia.dim_red_apoyo (
  red_key bigint generated by default as identity (start with 1 minvalue 0) primary key,
  red_apoyo_activa boolean unique,
  estado varchar(20) not null unique
);

-- Hecho 1. Grano: una evaluación clínica por estudiante y fecha.
create table if not exists datamart_resiliencia.fact_evaluacion_clinica (
  eval_key bigint generated always as identity primary key,
  fuente_evaluacion_id bigint not null unique,
  tiempo_key integer not null references datamart_resiliencia.dim_tiempo(tiempo_key),
  estudiante_key bigint not null references datamart_resiliencia.dim_estudiante(estudiante_key),
  terapeuta_key bigint not null references datamart_resiliencia.dim_terapeuta(terapeuta_key),
  sala_key bigint not null references datamart_resiliencia.dim_sala_terapia(sala_key),
  indice_resiliencia numeric(5,2) not null check (indice_resiliencia between 0 and 100),
  pensamientos_intrusivos integer not null check (pensamientos_intrusivos >= 0),
  periodo_referencia_dias smallint not null check (periodo_referencia_dias > 0),
  cantidad_sesiones smallint not null check (cantidad_sesiones >= 0)
);

-- Hecho 2. Grano: un registro de un hábito por estudiante y fecha.
create table if not exists datamart_resiliencia.fact_registro_habitos (
  registro_key bigint generated always as identity primary key,
  fuente_registro_id bigint not null unique,
  tiempo_key integer not null references datamart_resiliencia.dim_tiempo(tiempo_key),
  estudiante_key bigint not null references datamart_resiliencia.dim_estudiante(estudiante_key),
  habito_key bigint not null references datamart_resiliencia.dim_habito(habito_key),
  intensidad_key bigint not null references datamart_resiliencia.dim_intensidad(intensidad_key),
  completado_count smallint not null check (completado_count in (0, 1))
);

-- Hecho 3. Grano: una meta observada por estudiante y fecha.
create table if not exists datamart_resiliencia.fact_seguimiento_meta (
  seguimiento_key bigint generated always as identity primary key,
  fuente_registro_meta_id bigint not null unique,
  id_meta_oltp bigint not null,
  tiempo_key integer not null references datamart_resiliencia.dim_tiempo(tiempo_key),
  estudiante_key bigint not null references datamart_resiliencia.dim_estudiante(estudiante_key),
  meta_key bigint not null references datamart_resiliencia.dim_meta_categoria(meta_key),
  metas_cumplidas smallint not null check (metas_cumplidas in (0, 1)),
  metas_pendientes smallint not null check (metas_pendientes in (0, 1)),
  check (metas_cumplidas + metas_pendientes = 1)
);

-- Hecho 4. Grano: una evaluación de red de apoyo por estudiante y fecha.
create table if not exists datamart_resiliencia.fact_red_apoyo (
  red_apoyo_fact_key bigint generated always as identity primary key,
  fuente_evaluacion_red_id bigint not null unique,
  tiempo_key integer not null references datamart_resiliencia.dim_tiempo(tiempo_key),
  estudiante_key bigint not null references datamart_resiliencia.dim_estudiante(estudiante_key),
  terapeuta_key bigint not null references datamart_resiliencia.dim_terapeuta(terapeuta_key),
  red_key bigint not null references datamart_resiliencia.dim_red_apoyo(red_key),
  contactos_activos smallint not null check (contactos_activos >= 0),
  interacciones_sociales integer not null check (interacciones_sociales >= 0),
  periodo_referencia_dias smallint not null check (periodo_referencia_dias > 0)
);

create index if not exists ix_fact_eval_tiempo on datamart_resiliencia.fact_evaluacion_clinica(tiempo_key);
create index if not exists ix_fact_eval_estudiante on datamart_resiliencia.fact_evaluacion_clinica(estudiante_key);
create index if not exists ix_fact_habito_tiempo on datamart_resiliencia.fact_registro_habitos(tiempo_key);
create index if not exists ix_fact_meta_tiempo on datamart_resiliencia.fact_seguimiento_meta(tiempo_key);
create index if not exists ix_fact_meta_goal_time on datamart_resiliencia.fact_seguimiento_meta(id_meta_oltp, tiempo_key desc);
create index if not exists ix_fact_red_tiempo on datamart_resiliencia.fact_red_apoyo(tiempo_key);

